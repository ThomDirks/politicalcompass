"""Validate PCompass data and print or write an overview.

Usage:
  python tools/validate.py            check data, print overview
  python tools/validate.py --report   also write docs/party-overview.md
"""
import glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
model = json.load(open(os.path.join(ROOT, "data/model.json"), encoding="utf-8"))
AXES = model["axes"]
AXIS_IDS = [a["id"] for a in AXES]
FACETS = {f["id"]: a["id"] for a in AXES for f in a["facets"]}
LO, HI = model["scale"]["min"], model["scale"]["max"]
BAND = model["scale"]["centre_band"]
errors = []


def err(msg):
    errors.append(msg)


def axis_scores(facets):
    out = {}
    for a in AXES:
        vals = [facets[f["id"]][0] for f in a["facets"]]
        out[a["id"]] = sum(vals) / len(vals)
    return out


def type_code(scores):
    letters = []
    for a in AXES:
        s = scores[a["id"]]
        letters.append("x" if abs(s) < BAND else (a["neg"]["letter"] if s < 0 else a["pos"]["letter"]))
    return "".join(letters[:4]) + "-" + "".join(letters[4:])


actors = {}
for path in sorted(glob.glob(os.path.join(ROOT, "data/actors/*/*.json"))):
    a = json.load(open(path, encoding="utf-8"))
    rel = os.path.relpath(path, ROOT)
    for key in ("id", "type", "name", "country", "period", "status", "salience", "facets", "notes", "sources"):
        if key not in a:
            err(f"{rel}: missing '{key}'")
    if set(a.get("facets", {})) != set(FACETS):
        err(f"{rel}: facet set differs from model")
    for fid, val in a.get("facets", {}).items():
        if not (isinstance(val, list) and len(val) == 2):
            err(f"{rel}: {fid} must be [score, confidence]")
            continue
        s, c = val
        if not (LO <= s <= HI):
            err(f"{rel}: {fid} out of range ({s})")
        if c not in model["confidence"]:
            err(f"{rel}: {fid} bad confidence '{c}'")
    for ax in AXIS_IDS:
        if not 1 <= a.get("salience", {}).get(ax, 0) <= 5:
            err(f"{rel}: salience {ax} missing or out of 1..5")
        if not a.get("notes", {}).get(ax):
            err(f"{rel}: note {ax} missing")
    if a["id"] in actors:
        err(f"{rel}: duplicate id {a['id']}")
    actors[a["id"]] = a

frames = {}
for path in sorted(glob.glob(os.path.join(ROOT, "data/countries/*.json"))):
    fr = json.load(open(path, encoding="utf-8"))
    for pid in fr["parties"]:
        if pid not in actors:
            err(f"{os.path.relpath(path, ROOT)}: unknown party {pid}")
    frames[fr["code"]] = fr

if errors:
    print("\n".join(errors))
    sys.exit(1)


def centre(fr):
    total = sum(fr["parties"].values())
    c = {ax: 0.0 for ax in AXIS_IDS}
    for pid, w in fr["parties"].items():
        sc = axis_scores(actors[pid]["facets"])
        for ax in AXIS_IDS:
            c[ax] += sc[ax] * w / total
    return c


lines = []
head = "| Party | Code | " + " | ".join(AXIS_IDS) + " |"
sep = "|---|---|" + "---:|" * len(AXIS_IDS)
for code, fr in frames.items():
    cen = centre(fr)
    lines.append(f"\n## {fr['name']}\n")
    lines.append(head)
    lines.append(sep)
    for pid in sorted(fr["parties"], key=lambda p: -fr["parties"][p]):
        a = actors[pid]
        sc = axis_scores(a["facets"])
        lines.append(f"| {a['name']} | `{type_code(sc)}` | " + " | ".join(f"{sc[ax]:+.0f}" for ax in AXIS_IDS) + " |")
    lines.append(f"| *Centre ({fr['weight_basis'].split('(')[0].strip().rstrip('.')})* | `{type_code(cen)}` | " + " | ".join(f"*{cen[ax]:+.0f}*" for ax in AXIS_IDS) + " |")

overview = "\n".join(lines)
print(f"OK: {len(actors)} actors, {len(frames)} country frames")
print(overview)

if "--report" in sys.argv:
    legend = " · ".join(f"{a['id']} {a['neg']['letter']}/{a['pos']['letter']} = {a['neg']['label']}/{a['pos']['label']}" for a in AXES)
    doc = (
        "# Party overview\n\n"
        "Generated by `tools/validate.py --report`. Do not edit by hand.\n\n"
        "Axis scores are the mean of four facets, from -100 to +100. All profiles are **drafts** "
        "(see [model.md](model.md#status-of-the-current-profiles)). The centre row is the weighted "
        "mean of each country's parties.\n\n"
        f"Letters: {legend}. An x means within ±{BAND} of zero.\n"
        + overview + "\n"
    )
    open(os.path.join(ROOT, "docs/party-overview.md"), "w", encoding="utf-8").write(doc)
    print("\nwrote docs/party-overview.md")
